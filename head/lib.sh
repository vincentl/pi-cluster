#!/bin/bash
# Sourced by every script in head/: strict mode, settings from cluster.env, shared helpers.
# shellcheck disable=SC2034  # the variables below are used by the scripts that source this file

set -euo pipefail

REPO=$(cd "$(dirname "$0")/.." && pwd)
# shellcheck source=../cluster.env
source "$REPO/cluster.env"

IMAGE=/image/pi5                     # compute node root file system, exported read-only
NODE_NET=${NODE_SUBNET}.0/24         # compute node addresses
PREFIX=${CLUSTER_NET#*/}             # prefix length of the cluster network, 8 for 10.0.0.0/8
NODES=/etc/pi-cluster/nodes          # registry: one dnsmasq dhcp-host line per compute node
CACHE=/var/cache/pi-cluster          # downloaded OS images
CHANGED=0                            # put sets this to 1 when it writes a file
GENERATED="# generated by pi-cluster (head/${0##*/}); edits are overwritten"

log() { printf '==> %s\n' "$*"; }
die() { printf 'error: %s\n' "$*" >&2; exit 1; }
need_root() { [[ $EUID -eq 0 ]] || die "run this with sudo"; }

# Compute node N: node_name 7 is pi-007, node_ip 7 is 10.0.1.7.
node_name() { printf '%s%03d\n' "$NODE_PREFIX" "$((10#$1))"; }
node_ip() { printf '%s.%d\n' "$NODE_SUBNET" "$((10#$1))"; }

# The device that holds /, for example /dev/mmcblk0p2 or /dev/nvme0n1p2.
root_source() { findmnt -n -o SOURCE /; }

# Write stdin to FILE (mode MODE, default 644) unless FILE already has exactly that content.
put() {
    local file=$1 mode=${2:-644} tmp
    tmp=$(mktemp)
    cat > "$tmp"
    if cmp -s "$tmp" "$file"; then
        rm -f "$tmp"
        return 0
    fi
    install -D -m "$mode" "$tmp" "$file"
    rm -f "$tmp"
    CHANGED=1
    log "wrote $file"
}

# Install whichever of the given packages are missing.
need_packages() {
    local missing=() pkg
    for pkg in "$@"; do
        [[ $(dpkg-query -W -f '${db:Status-Status}' "$pkg" 2>/dev/null) == installed ]] || missing+=("$pkg")
    done
    [[ ${#missing[@]} -gt 0 ]] || return 0
    log "installing ${missing[*]}"
    apt-get update
    DEBIAN_FRONTEND=noninteractive apt-get install -y "${missing[@]}"
}

# /etc/hosts for the head node and the image: the head node and every registered compute node.
hosts_file() {
    echo "# generated by pi-cluster from cluster.env and $NODES; edits are overwritten"
    printf '%-15s %s\n' 127.0.0.1 localhost ::1 'localhost ip6-localhost ip6-loopback' \
        ff02::1 ip6-allnodes ff02::2 ip6-allrouters "$HEAD_IP" "$HEAD_NODE"
    if [[ -e $NODES ]]; then
        # Registry lines are MAC,IP,NAME, optionally followed by "# serial XXXXXXXX".
        sed -e 's/[[:space:]]*#.*//' -e '/^$/d' "$NODES" | awk -F, '{ printf "%-15s %s\n", $2, $3 }'
    fi
}
