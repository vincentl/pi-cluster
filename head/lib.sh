#!/bin/bash
# Sourced by every script in head/: strict mode, settings from cluster.env, shared helpers.
# shellcheck disable=SC2034  # the variables below are used by the scripts that source this file

set -euo pipefail

REPO=$(cd "$(dirname "$0")/.." && pwd)
# shellcheck source=../cluster.env
source "$REPO/cluster.env"

IMAGE=/image/pi5                     # compute node root file system, exported read-only
NODE_NET=${NODE_SUBNET}.0/24         # compute node addresses
PREFIX=${CLUSTER_NET#*/}             # prefix length of the cluster network, 8 for 10.0.0.0/8
NODES=/etc/pi-cluster/nodes          # registry: one dnsmasq dhcp-host line per compute node
CACHE=/var/cache/pi-cluster          # downloaded OS images
CHANGED=0                            # put sets this to 1 when it writes a file
GENERATED="# generated by pi-cluster (head/${0##*/}); edits are overwritten"

log() { printf '==> %s\n' "$*"; }
die() { printf 'error: %s\n' "$*" >&2; exit 1; }
need_root() { [[ $EUID -eq 0 ]] || die "run this with sudo"; }

# Everything in head/ runs on the head node: stop at once anywhere else, such as a workstation.
[[ $(tr -d '\0' 2>/dev/null < /proc/device-tree/model) == "Raspberry Pi"* ]] ||
    die "this script runs on the head node, not on $(hostname -s); ssh $HEAD_NODE first"

# Compute node N: node_name 7 is pi-007, node_ip 7 is 10.0.1.7.
node_name() { printf '%s%03d\n' "$NODE_PREFIX" "$((10#$1))"; }
node_ip() { printf '%s.%d\n' "$NODE_SUBNET" "$((10#$1))"; }

# The device that holds /, for example /dev/mmcblk0p2 or /dev/nvme0n1p2.
root_source() { findmnt -n -o SOURCE /; }

# Write stdin to FILE (mode MODE, default 644) unless FILE already has exactly that content.
put() {
    local file=$1 mode=${2:-644} tmp
    tmp=$(mktemp)
    cat > "$tmp"
    if cmp -s "$tmp" "$file"; then
        rm -f "$tmp"
        return 0
    fi
    install -D -m "$mode" "$tmp" "$file"
    rm -f "$tmp"
    CHANGED=1
    log "wrote $file"
}

# Install whichever of the given packages are missing; leading options go to apt-get install.
need_packages() {
    local opts=() missing=() pkg
    while [[ ${1:-} == -* ]]; do opts+=("$1"); shift; done
    for pkg in "$@"; do
        [[ $(dpkg-query -W -f '${db:Status-Status}' "$pkg" 2>/dev/null) == installed ]] || missing+=("$pkg")
    done
    [[ ${#missing[@]} -gt 0 ]] || return 0
    log "installing ${missing[*]}"
    apt-get update
    DEBIAN_FRONTEND=noninteractive apt-get install -y "${opts[@]}" "${missing[@]}"
}

# Run a command inside the compute image; is a package installed there?
image_run() { bash "$REPO/head/image-run.sh" "$@"; }
image_has() {
    [[ $(dpkg-query --admindir="$IMAGE/var/lib/dpkg" -W -f '${db:Status-Status}' "$1" 2>/dev/null) == installed ]]
}

# The head node's users, groups and passwords in the image, so every account has one UID everywhere.
copy_accounts() {
    local f
    for f in passwd shadow group gshadow; do
        cmp -s "/etc/$f" "$IMAGE/etc/$f" || { cp -p "/etc/$f" "$IMAGE/etc/$f"; log "copied /etc/$f into the image"; }
    done
}

# /etc/hosts for the head node and the image: the head node and every registered compute node.
hosts_file() {
    echo "# generated by pi-cluster from cluster.env and $NODES; edits are overwritten"
    printf '%-15s %s\n' 127.0.0.1 localhost ::1 'localhost ip6-localhost ip6-loopback' \
        ff02::1 ip6-allnodes ff02::2 ip6-allrouters "$HEAD_IP" "$HEAD_NODE"
    if [[ -e $NODES ]]; then
        # Registry lines are MAC,IP,NAME, optionally followed by "# serial XXXXXXXX"; list them by
        # name, since a re-registered node's line goes to the end of the registry.
        sed -e 's/[[:space:]]*#.*//' -e '/^$/d' "$NODES" | awk -F, '{ printf "%-15s %s\n", $2, $3 }' |
            LC_ALL=C sort -k 2,2
    fi
}

# /etc/ssh/ssh_known_hosts for the head node and the image: the nodes' shared host keys, by name
# pattern and address, and the head node's, so ssh between them never asks.
known_hosts_file() {
    local f
    echo "# generated by pi-cluster from the host keys of $IMAGE and $HEAD_NODE; edits are overwritten"
    for f in "$IMAGE"/etc/ssh/ssh_host_*_key.pub; do
        [[ -e $f ]] || continue
        printf '%s???,%s.* %s\n' "$NODE_PREFIX" "$NODE_SUBNET" "$(cut -d ' ' -f 1,2 "$f")"
    done
    for f in /etc/ssh/ssh_host_*_key.pub; do
        [[ -e $f ]] || continue
        printf '%s,%s %s\n' "$HEAD_NODE" "$HEAD_IP" "$(cut -d ' ' -f 1,2 "$f")"
    done
}

# The registered compute nodes' names, one per line, sorted.
registered_nodes() {
    [[ -e $NODES ]] || return 0
    sed -e 's/[[:space:]]*#.*//' -e '/^$/d' "$NODES" | cut -d, -f3 | sort
}

# Slurm on the head node, once 25-slurm.sh has installed it: its settings list the registered
# nodes, and slurmctld runs with them. slurmctld will not start without a node.
slurm_update() {
    local nodes
    [[ $(dpkg-query -W -f '${db:Status-Status}' slurmctld 2>/dev/null) == installed ]] || return 0
    nodes=$(registered_nodes | paste -sd, -)
    [[ -n $nodes ]] || return 0
    CHANGED=0
    put /etc/slurm/cgroup.conf <<EOF
# generated by pi-cluster from cluster.env; edits are overwritten
ConstrainCores=yes
ConstrainRAMSpace=yes
ConstrainSwapSpace=yes
EOF
    put /etc/slurm/slurm.conf <<EOF
# generated by pi-cluster from cluster.env and $NODES; edits are overwritten.
# Your own settings go in slurm-local.conf, included at the end.
ClusterName=pi-cluster
SlurmctldHost=$HEAD_NODE($HEAD_IP)
SlurmctldParameters=enable_configless
SlurmUser=slurm
AuthType=auth/slurm
CredType=cred/slurm
StateSaveLocation=/var/lib/slurm/slurmctld
SlurmdSpoolDir=/var/lib/slurm/slurmd
ReturnToService=2
ProctrackType=proctrack/cgroup
TaskPlugin=task/cgroup,task/affinity
SelectType=select/cons_tres
SelectTypeParameters=CR_Core_Memory
DefMemPerCPU=$((NODE_MEMORY / NODE_CPUS))
NodeName=$nodes CPUs=$NODE_CPUS RealMemory=$NODE_MEMORY
PartitionName=main Nodes=ALL Default=YES MaxTime=INFINITE State=UP
Include slurm-local.conf
EOF
    [[ -e /etc/slurm/slurm-local.conf ]] || put /etc/slurm/slurm-local.conf <<EOF
# Your own Slurm settings, read after slurm.conf. pi-cluster never changes this file.
# After editing it, run: sudo scontrol reconfigure
EOF
    if ! systemctl is-active --quiet slurmctld; then
        systemctl enable --now --quiet slurmctld
        log "started slurmctld"
    elif (( CHANGED )); then
        scontrol reconfigure
        log "slurmctld reloaded its settings (scontrol reconfigure)"
    fi
}
